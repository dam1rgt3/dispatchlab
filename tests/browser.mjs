import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';

const url = process.env.DEMO_URL || 'http://127.0.0.1:8090/';
const browser = await chromium.launch();
try {
  const page = await browser.newPage({viewport:{width:1440,height:960}});
  const errors = [];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('dialog',dialog=>dialog.accept());
  const button = name => page.getByRole('button',{name,exact:true});
  const choose = title => page.getByRole('button',{name:new RegExp(title)}).first().click();
  const has = async text => { await page.getByText(text,{exact:true}).first().waitFor(); };
  await page.goto(url,{waitUntil:'networkidle'});
  await has('All seven visits are assigned');
  await choose('Technician out');
  await button('Assign Anna').click();
  await choose('Cedar Park.*Thermostat setup');
  await button('Hold for customer approval').click();
  await has('On hold');
  await button('Customer declined').click();
  await button('Assign Alex').click();
  await has('7 assigned · 0 open');
  await button('Undo').click();
  await has('6 assigned · 1 open');
  await button('Hold for customer approval').click();
  await button('Customer agreed · assign').click();
  await has('7 assigned · 0 open');
  await button('Original').click();
  assert.equal(await page.locator('.slot.revised').count(),0);
  await button('Current').click();
  assert.equal(await page.locator('.slot.revised').count(),2);
  await choose('Job running late');
  await has('Anna now finishes at 12:35 (+100 min).');
  await button('Assign Anna').click();
  await has('7 assigned · 0 open');
  await choose('Urgent request');
  await button('Assign Michael').click();
  await has('8 assigned · 0 open');
  await button('Reset day').click();
  await choose('Write a dispatch note');
  const input=page.getByRole('textbox',{name:'Dispatch note in English'});
  await input.fill('Order pizza');
  await button('Preview note').click();
  await has('I could not distinguish the incident. Try an absence, a delay in minutes or an urgent visit.');
  await input.fill('Anna is running 45 minutes late');
  await button('Preview note').click();
  await button('Use this incident').click();
  await has('Schedule still works');
  await page.setViewportSize({width:390,height:844});
  await choose('Technician out');
  await button('Assign Anna').click();
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth <= window.innerWidth+1),'Page should fit the mobile viewport');
  assert.deepEqual(errors,[]);
  console.log('Browser checks passed for all three scenarios, customer approval, note intake, undo and mobile at '+url);
} finally { await browser.close(); }
